#pragma once

#include "core/templates/hash_map.h"

// Tracks how long the user works in the editor and exposes it as a
// per-day activity heatmap (in minutes), similar to GitHub contributions.
class ActivityTracker {
public:
	static String get_log_path();

	// Called when an editor session starts / ends.
	static void begin_session();
	static void end_session();

	// Returns a map of local-midnight unix timestamps to active minutes.
	static HashMap<int64_t, int64_t> get_daily_minutes();
};
